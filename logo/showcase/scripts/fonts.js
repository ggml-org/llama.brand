// Copies Llama Sans from ../../fonts/variable into src/lib/fonts with plain names (brackets in file
// names trip up bundlers) and writes their @font-face rules. Runs before dev, build and check.
import { copyFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const from = fileURLToPath(new URL('../../../fonts/variable/', import.meta.url));
const to = fileURLToPath(new URL('../src/lib/fonts/', import.meta.url));
mkdirSync(to, { recursive: true });

const faces = ['Display', 'UI', 'Text'].map((v) => {
	copyFileSync(`${from}LlamaSans${v}[wght].ttf`, `${to}LlamaSans${v}-VF.ttf`);
	return `@font-face { font-family: "Llama Sans ${v}"; font-weight: 400 700; font-display: block; src: url("./LlamaSans${v}-VF.ttf") format("truetype"); }`;
});
writeFileSync(`${to}fonts.css`, `/* generated by scripts/fonts.js */\n${faces.join('\n')}\n`);
console.log(`copied ${faces.length} fonts to src/lib/fonts`);
