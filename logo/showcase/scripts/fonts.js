// Copies Llama Sans and Llama Mono from ../../fonts/variable into src/lib/fonts with plain names (brackets in file
// names trip up bundlers) and writes their @font-face rules. Runs before dev, build and check.
import { copyFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const from = fileURLToPath(new URL('../../../fonts/variable/', import.meta.url));
const to = fileURLToPath(new URL('../src/lib/fonts/', import.meta.url));
mkdirSync(to, { recursive: true });

// Llama Sans, one font over wght and opsz (browsers set the optical size from font-size), and Llama Mono for the
// specs and labels set in mono
copyFileSync(`${from}LlamaSans[opsz,wght].ttf`, `${to}LlamaSans-VF.ttf`);
copyFileSync(`${from}LlamaMono[wght].ttf`, `${to}LlamaMono-VF.ttf`);
const faces = ['Llama Sans', 'Llama Mono'].map(
	(family) =>
		`@font-face { font-family: "${family}"; font-weight: 400 700; font-display: block; src: url("./${family.replace(' ', '')}-VF.ttf") format("truetype"); }`
);
writeFileSync(`${to}fonts.css`, `/* generated by scripts/fonts.js */\n${faces.join('\n')}\n`);
console.log(`copied ${faces.length} fonts to src/lib/fonts`);
